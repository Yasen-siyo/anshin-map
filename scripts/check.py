def main():
    for rid, places in PLACES.items():
        if not (WEB / rid / "meta.json").exists():
            continue
        meta = json.loads((WEB / rid / "meta.json").read_text())
        a = np.asarray(Image.open(WEB / rid / "anshin.png"))
        (s, w), (n, e) = meta["bounds"]
        y = lambda lat: math.log(math.tan(math.pi / 4 + math.radians(lat) / 2))  # noqa: E731
        print(f"== {meta['name']}" + ("" if meta.get("crime_src") else " (범죄 자료 없음, 시설만)"))
        for name, (lat, lon) in places.items():
            j = int((lon - w) / (e - w) * meta["nx"])
            i = int((y(n) - y(lat)) / (y(n) - y(s)) * meta["ny"])
            win = a[max(i - 2, 0):i + 3, max(j - 2, 0):j + 3, 0]
            note = "" if a[i, j, 1] else "  데이터 없음"
            print(f"{name:16s} {a[i, j, 0]:3d}  (주변 250m 최저 {win.min()}){note}")


if __name__ == "__main__":
    main()
